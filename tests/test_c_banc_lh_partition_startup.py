def test_partial_raw_and_late_publication_invalidation(tmp_path: Path, monkeypatch):
    raw = {}

    def fail(stage):
        if stage == "muscle_command":
            raise TimeoutError("fixture checkpoint")

    with pytest.raises(TimeoutError, match="fixture checkpoint"):
        analyze(fixture(), raw=raw, progress=fail)
    assert raw["muscle_joint_contribution"].shape == (301, 42, 96)
    report, raw = analyze(fixture())
    result = {"validity": "valid_saved_diagnostic", "H258_same_muscle": True,
              "analysis": report, "finalization_pending": True}
    original = e258.publish
    attempts = 0

    def late_once(*args, **kwargs):
        nonlocal attempts
        attempts += 1
        original(*args, **kwargs)
        if attempts == 1:
            raise OSError("fixture late publication")

    monkeypatch.setattr(e258, "publish", late_once)
    error = e258.settle(tmp_path, result, {"x": np.array([1.])},
                        {"errors": []}, lambda: 1., float("inf"))
    assert isinstance(error, OSError)
    assert result["H258_same_muscle"] is None
    assert result["analysis"]["H258_same_muscle"] is None
    assert result["analysis"]["endpoint_projections"]["first_new_violation"]["muscle41_dominates"] is None
    saved = json.loads((tmp_path / "result.json").read_text(encoding="utf-8"))
    assert saved["validity"] == "incomplete_or_invalid"
    manifest = json.loads((tmp_path / "output-manifest.json").read_text(encoding="utf-8"))
    assert manifest["files"]["errors.json"]["sha256"] == e258.sha(tmp_path / "errors.json")
    persistent = tmp_path / "persistent"
    persistent.mkdir()
    second_report, _ = analyze(fixture())
    pending = {"validity": "valid_saved_diagnostic", "H258_same_muscle": True,
               "analysis": second_report, "finalization_pending": True}

    def always_fail(*_args, **_kwargs):
        raise OSError("fixture persistent publication")

    monkeypatch.setattr(e258, "publish", always_fail)
    error = e258.settle(persistent, pending, {}, {"errors": []},
                        lambda: 1., float("inf"))
    assert isinstance(error, OSError)
    assert pending["H258_same_muscle"] is None
    assert pending["finalization_pending"] is True
    assert not (persistent / "output-manifest.json").exists()
    saved = json.loads((persistent / "result.json").read_text(encoding="utf-8"))
    assert saved["errors"] == json.loads((persistent / "errors.json").read_text(encoding="utf-8"))
    assert saved["errors"] == json.loads((persistent / "ledger.json").read_text(encoding="utf-8"))["errors"]


