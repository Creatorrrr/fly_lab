def test_late_publication_revokes_nested_support_and_latest_manifest(tmp_path: Path,
                                                                      monkeypatch):
    result = {"validity": "valid_saved_diagnostic",
              "H252_local_startup_supported": True,
              "analysis": {"hypothesis_supported": True},
              "finalization_pending": True}
    ledger = {"errors": []}
    raw = {"x": np.array([1.])}
    original = e252.publish
    count = 0
    def late_once(*args, **kwargs):
        nonlocal count
        count += 1
        original(*args, **kwargs)
        if count == 1:
            raise OSError("generated late failure")
    monkeypatch.setattr(e252, "publish", late_once)
    error = e252.settle(tmp_path, result, raw, ledger, lambda: 1., float("inf"))
    assert isinstance(error, OSError)
    assert result["H252_local_startup_supported"] is None
    assert result["analysis"]["hypothesis_supported"] is None
    saved = json.loads((tmp_path / "result.json").read_text(encoding="utf-8"))
    assert saved["validity"] == "incomplete_or_invalid"
    manifest = json.loads((tmp_path / "output-manifest.json").read_text(encoding="utf-8"))
    assert manifest["files"]["errors.json"]["sha256"] == e252.sha(tmp_path / "errors.json")
    assert manifest["files"]["ledger.json"]["sha256"] == e252.sha(tmp_path / "ledger.json")


def test_persistent_publication_failure_has_no_success_manifest(tmp_path: Path,
                                                                 monkeypatch):
    result = {"validity": "valid_saved_diagnostic",
              "H252_local_startup_supported": True,
              "analysis": {"hypothesis_supported": True},
              "finalization_pending": True}
    def fail(*_args, **_kwargs):
        raise OSError("generated persistent publication fault")
    monkeypatch.setattr(e252, "publish", fail)
    error = e252.settle(tmp_path, result, {}, {"errors": []},
                        lambda: 1., float("inf"))
    assert isinstance(error, OSError)
    assert result["H252_local_startup_supported"] is None
    assert result["analysis"]["hypothesis_supported"] is None
    assert result["finalization_pending"] is True
    assert not (tmp_path / "output-manifest.json").exists()
    saved = json.loads((tmp_path / "result.json").read_text(encoding="utf-8"))
    assert saved["validity"] == "incomplete_or_invalid"


